#!/usr/bin/env node
/**
 * Clone the hand-built TOOL routes of one locale into another.
 *
 *   node scripts/clone-locale-routes.mjs pt de [--skip id,id] [--dry-run]
 *
 * A hand-built tool route is three lines of wiring — import the tool's
 * content module, render ToolPageShell around the tool component — so every
 * locale's copy is the same file with a different locale suffix and folder
 * name. This writes src/app/<to>/<to-slug>/page.tsx for every tool route in
 * src/app/<from>/, swapping `.<from>"` imports for `.<to>"`.
 *
 * Deliberately NOT cloned (each needs its own copy or is generated):
 *   • generated routes — gen-variants ("Generated by" header) and
 *     gen-converters (<ConverterPage>) write those from status.ts; run them
 *     after shipping;
 *   • static pages (home, pricing, legal, auth) — their metadata is
 *     hand-written in the target language;
 *   • tools the target does not ship (--skip).
 *
 * Existing target files are never overwritten. Slugs come from the authored
 * <XX>_TOOL_SLUGS maps in slugs.ts, read as text like every other script.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(root, "src");
const [from, to] = process.argv.slice(2).filter((a) => !a.startsWith("--") && !a.includes(","));
const skipArg = process.argv.find((a, i) => process.argv[i - 1] === "--skip") ?? "";
const skip = new Set(skipArg.split(",").filter(Boolean));
const dry = process.argv.includes("--dry-run");
if (!from || !to) {
  console.error("usage: node scripts/clone-locale-routes.mjs <from> <to> [--skip id,id] [--dry-run]");
  process.exit(2);
}

const slugsSrc = readFileSync(join(SRC, "i18n/slugs.ts"), "utf8").replace(/\r\n/g, "\n");
const slugMap = (loc) => {
  const m = new RegExp(`const ${loc.toUpperCase()}_TOOL_SLUGS[^{]*\\{([\\s\\S]*?)\\n\\};`).exec(slugsSrc);
  if (!m) throw new Error(`no ${loc.toUpperCase()}_TOOL_SLUGS in slugs.ts`);
  return Object.fromEntries([...m[1].matchAll(/^\s*"([^"]+)":\s*"([^"]+)"/gm)].map((x) => [x[1], x[2]]));
};
const fromSlugs = slugMap(from);
const toSlugs = slugMap(to);
const idByFromSlug = Object.fromEntries(Object.entries(fromSlugs).map(([id, s]) => [s, id]));

let written = 0;
const skipped = [];
for (const dir of readdirSync(join(SRC, "app", from), { withFileTypes: true })) {
  if (!dir.isDirectory()) continue;
  const id = idByFromSlug[dir.name];
  if (!id) continue; // a static page
  const file = join(SRC, "app", from, dir.name, "page.tsx");
  if (!existsSync(file)) continue;
  const text = readFileSync(file, "utf8");
  // gen-variants marks its files; gen-converters' ConverterPage routes carry no
  // marker, so recognise them by what they render.
  if (/Generated by|<ConverterPage /.test(text)) continue;
  if (skip.has(id)) { skipped.push(id); continue; }
  const target = join(SRC, "app", to, toSlugs[id], "page.tsx");
  if (existsSync(target)) continue;
  const out = text.replaceAll(`.${from}"`, `.${to}"`);
  if (out.includes(`.${from}"`) || new RegExp(`["/]${from}["/]`).test(out))
    throw new Error(`${file}: still references "${from}" after the swap — clone it by hand`);
  if (!dry) {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, out);
  }
  written++;
}
console.log(`${dry ? "[dry-run] " : ""}${written} route(s) cloned ${from} → ${to}${skipped.length ? `; skipped ${skipped.join(", ")}` : ""}.`);
