/**
 * Generate the route stub for every VARIANT tool (a `tools.ts` entry with a
 * `parentId`): "Compress Image to 50KB" is compress-image's own component with
 * `preset={{ targetKb: 50 }}`, on its own URL with its own copy.
 *
 * Same reasoning as gen-converters.mjs: a static export has no dynamic routes,
 * so each variant is a real folder whose page.tsx differs from its siblings only
 * in ids — exactly the copy-paste that ships two pages on one slug, or a stub
 * importing the wrong locale's module, with no build error at all.
 *
 *   npm run gen:variants              write any missing/changed stubs
 *   npm run gen:variants -- --check   exit 1 if anything is out of date (prebuild)
 *
 * Read without a TS toolchain, like every other gate here:
 *   • variants   — tools.ts entries sliced on `    id:` boundaries; the entry's
 *                  `parentId: "…"` and one-line `preset: { … }` literal. The
 *                  literal is copied VERBATIM into the stub, so TypeScript
 *                  checks it against the parent component's `preset` prop.
 *   • component  — the parent's English page.tsx, from its
 *                  `import { XTool } from "./XTool";` line.
 *   • locales    — LOCALE_META keys (config.ts), SHIPPED_TOOLS (status.ts) and
 *                  <LOC>_TOOL_SLUGS (slugs.ts), as gen-converters reads them.
 *
 * A localized stub is written only when the variant ships in that locale; the
 * parent must ship there too, because the stub imports the parent's module.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const appDir = join(root, "src", "app");
const read = (...p) => readFileSync(join(root, ...p), "utf8").replace(/\r\n/g, "\n");

const fail = (msg) => {
  console.error(msg);
  process.exit(1);
};

// ── Locales ────────────────────────────────────────────────────────────────
const metaBlock = /export const LOCALE_META = \{([\s\S]*?)\n\} as const/.exec(read("src", "i18n", "config.ts"))?.[1] ?? "";
const LOCALES = [...metaBlock.matchAll(/^  ([a-z]{2}(?:-[A-Za-z]+)?): \{/gm)].map((m) => m[1]).filter((l) => l !== "en");
if (LOCALES.length === 0) fail("Parsed zero translated locales from config.ts LOCALE_META — has its shape changed?");

// ── Variants from the registry ─────────────────────────────────────────────
const toolsSrc = read("src", "lib", "tools.ts");
const idMatches = [...toolsSrc.matchAll(/^ {4}id:\s*"([^"]+)",/gm)];
if (idMatches.length < 40) fail(`Parsed only ${idMatches.length} tools from tools.ts — has its shape changed?`);
const entries = idMatches.map((m, i) => {
  const body = toolsSrc.slice(m.index, i + 1 < idMatches.length ? idMatches[i + 1].index : toolsSrc.length);
  return {
    id: m[1],
    body,
    parentId: /^ {4}parentId:\s*"([^"]+)",/m.exec(body)?.[1],
    preset: /^ {4}preset:\s*(\{.*\}),\s*$/m.exec(body)?.[1],
    hasPresetLine: /^ {4}preset:/m.test(body),
    status: /^ {4}status:\s*"([^"]+)"/m.exec(body)?.[1],
  };
});
const byId = new Map(entries.map((e) => [e.id, e]));
const variants = entries.filter((e) => e.parentId);

for (const v of variants) {
  const parent = byId.get(v.parentId);
  if (!parent) fail(`${v.id}: parentId "${v.parentId}" is not a tool id`);
  if (parent.parentId) fail(`${v.id}: parent "${v.parentId}" is itself a variant — families are one level deep`);
  if (!v.preset) {
    fail(
      v.hasPresetLine
        ? `${v.id}: preset must be a ONE-LINE object literal ending in "},", e.g. preset: { targetKb: 50 },`
        : `${v.id}: a variant needs a preset`,
    );
  }
}

/** `import { CompressTool } from "./CompressTool";` in the parent's English route. */
function parentComponent(parentId) {
  const file = join(appDir, parentId, "page.tsx");
  if (!existsSync(file)) fail(`no src/app/${parentId}/page.tsx to read the parent component from`);
  const m = /^import \{ (\w+) \} from "\.\/(\w+)";$/m.exec(read("src", "app", parentId, "page.tsx"));
  if (!m) fail(`src/app/${parentId}/page.tsx has no \`import { X } from "./X";\` line — can't tell which component to render`);
  return { name: m[1], from: `@/app/${parentId}/${m[2]}` };
}

const stub = (v, locale) => {
  const comp = parentComponent(v.parentId);
  return `// Generated by scripts/gen-variants.mjs from lib/tools.ts — do not edit by hand.
import { ToolPageShell } from "@/components/ToolPageShell";
import { toolMetadata } from "@/lib/i18n/tool-meta";
import content from "@/content/tools/${v.id}.${locale}";
import parent from "@/content/tools/${v.parentId}.${locale}";
import { ${comp.name} } from "${comp.from}";

export const metadata = toolMetadata(content);

export default function Page() {
  return (
    <ToolPageShell content={content} parent={parent}>
      <${comp.name} preset={${v.preset}} />
    </ToolPageShell>
  );
}
`;
};

// ── Localized routes ───────────────────────────────────────────────────────
const statusSrc = read("src", "i18n", "status.ts");
const slugsSrc = read("src", "i18n", "slugs.ts");
function shippedIn(locale) {
  const tools = /const SHIPPED_TOOLS[\s\S]*?\n\};/.exec(statusSrc)?.[0] ?? "";
  const block = new RegExp(`^  ${locale}: \\[([\\s\\S]*?)^  \\]`, "m").exec(tools);
  return new Set([...(block?.[1] ?? "").replace(/\/\/.*$/gm, "").matchAll(/"([a-z0-9-]+)"/g)].map((m) => m[1]));
}
function slugMap(locale) {
  const block = new RegExp(`${locale.toUpperCase()}_TOOL_SLUGS[^{]*\\{([\\s\\S]*?)^\\};`, "m").exec(slugsSrc);
  return Object.fromEntries([...(block?.[1] ?? "").matchAll(/"([a-z0-9-]+)":\s*"([a-z0-9-]+)"/g)].map((m) => [m[1], m[2]]));
}

const targets = [];
for (const v of variants) targets.push({ v, locale: "en", dir: join(appDir, v.id) });
for (const locale of LOCALES) {
  const shipped = shippedIn(locale);
  const slugs = slugMap(locale);
  for (const v of variants) {
    if (!shipped.has(v.id)) continue;
    if (!slugs[v.id]) fail(`${v.id} ships in ${locale} but has no ${locale.toUpperCase()}_TOOL_SLUGS entry`);
    if (!shipped.has(v.parentId)) fail(`${v.id} ships in ${locale} but its parent ${v.parentId} does not`);
    targets.push({ v, locale, dir: join(appDir, locale, slugs[v.id]) });
  }
}

// ── Write / check ──────────────────────────────────────────────────────────
const check = process.argv.includes("--check");
let stale = 0;
let written = 0;
for (const { v, locale, dir } of targets) {
  const file = join(dir, "page.tsx");
  const rel = relative(root, file).replace(/\\/g, "/");
  const want = stub(v, locale);
  // Line-ending blind, as in gen-converters (core.autocrlf hands back CRLF).
  const have = existsSync(file) ? readFileSync(file, "utf8").replace(/\r\n/g, "\n") : null;
  if (have === want) continue;
  if (check) {
    console.error(`out of date: ${rel}`);
    stale++;
    continue;
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, want, "utf8");
  console.log(`${have === null ? "created" : "updated"}: ${rel}`);
  written++;
}

if (check && stale > 0) fail(`\n${stale} variant stub(s) out of date. Run: npm run gen:variants`);
console.log(
  check
    ? `All ${targets.length} variant stubs up to date (${variants.length} variants).`
    : `${variants.length} variants, ${targets.length} routes, ${written} stub(s) written.`,
);
